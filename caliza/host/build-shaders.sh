#!/usr/bin/env bash
# Compiles Caliza's original Estratos shaders to an embeddable SPIR-V include.
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
out="$root/caliza/native/estratos_shaders.inc"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
validator=${GLSLANG_VALIDATOR:-glslangValidator}
{
  echo '// Generated by caliza/host/build-shaders.sh. Do not edit.'
  for src in "$root"/caliza/shaders/*.vert "$root"/caliza/shaders/*.frag; do
    base=$(basename "$src")
    name=${base%.*}
    stage=${base##*.}
    "$validator" -V --target-env vulkan1.1 -o "$tmp/$name.$stage.spv" "$src" >"$tmp/log" 2>&1 || { cat "$tmp/log" >&2; exit 1; }
    python3 - "$tmp/$name.$stage.spv" "caliza_spv_${name}_${stage}" <<'PY'
import struct, sys
data = open(sys.argv[1], 'rb').read()
words = struct.unpack('<%dI' % (len(data) // 4), data)
print('static const uint32_t %s[] = {' % sys.argv[2])
for i in range(0, len(words), 8):
    print('\t' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
print('};')
PY
  done
} >"$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
